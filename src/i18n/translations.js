export const DEFAULT_LANGUAGE = 'en';

export const normalizeLanguage = (value) => {
  const normalized = String(value || '')
    .trim()
    .toLowerCase()
    .split(/[-_]/)[0];
  return SUPPORTED_LANGUAGES.some(({ code }) => code === normalized)
    ? normalized
    : DEFAULT_LANGUAGE;
};

